/**
 * Enriquece un ítem con los metadatos oficiales del catálogo maestro (producto, coordinador, trafiker, grupo, dailyBudget)
 */
export function enrichItemWithCatalog(item) {
  if (!item) return item;
  const match = findInCatalog(item.name) || (item.phone ? findInCatalog(item.phone) : null);
  return {
    ...item,
    phone: item.phone || (match ? match.phone : ''),
    category: item.category || (match ? match.category : 'GENERAL'),
    product: item.product || (match ? match.product : item.category || 'GENERAL'),
    coordinator: item.coordinator || (match ? match.coordinator : 'SIN ASIGNAR'),
    trafiker: item.trafiker || (match ? match.trafiker : 'SIN ASIGNAR'),
    group: item.group || (match ? match.group : ''),
    status: item.status || (match ? match.status : 'ACTIVA'),
    dailyBudget: item.dailyBudget !== undefined ? item.dailyBudget : (match ? match.dailyBudget : 0)
  };
}

