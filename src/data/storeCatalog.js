export function normalizeName(str) {
  if (!str) return '';
  return String(str)
    .replace(/^\+?\d{7,15}\s*([·\-\|:]\s*)?/, '')
    .replace(/\s*\(\+?\d{7,15}\)\s*$/, '')
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Busca una tienda en el catálogo maestro mediante concordancia exacta o difusa (fuzzy match)
 */
export function findInCatalog(storeName) {
  if (!storeName) return null;
  const rawStr = String(storeName).trim();

  // 0. Concordancia por número de teléfono
  const rawDigits = rawStr.replace(/[^0-9]/g, '');
  if (rawDigits.length >= 10) {
    const last10 = rawDigits.slice(-10);
    const byPhone = STORE_CATALOG.find(item => item.phone && item.phone.replace(/[^0-9]/g, '').slice(-10) === last10);
    if (byPhone) return byPhone;
  }

  const cleanInput = normalizeName(storeName);
  if (!cleanInput) return null;

  // 1. Concordancia exacta
  const exact = STORE_CATALOG.find(item => normalizeName(item.name) === cleanInput);
  if (exact) return exact;

  // 1.1 Si tiene sufijo entre paréntesis con número/teléfono (ej: "NET CAPITAL 3 (3117983168)" o "TODO EN LINEA 1 (9919) (3117689919)")
  const strippedSuffix = rawStr.replace(/\s*\(\+?\d+\)\s*$/, '').trim();
  if (strippedSuffix && strippedSuffix !== rawStr) {
    const strippedExact = STORE_CATALOG.find(item => normalizeName(item.name) === normalizeName(strippedSuffix));
    if (strippedExact) return strippedExact;
    const strippedClean = strippedSuffix.replace(/^\+?\d{7,15}\s*([·\-\|:]\s*)?/, '').trim();
    if (strippedClean && strippedClean !== strippedSuffix) {
      const coreExact = STORE_CATALOG.find(item => normalizeName(item.name) === normalizeName(strippedClean));
      if (coreExact) return coreExact;
    }
  }

  const inputNums = cleanInput.match(/\d+/g)?.join('-') || '';

  // 2. Concordancia de contención mutua respetando números de línea/tienda
  const partial = STORE_CATALOG.find(item => {
    const norm = normalizeName(item.name);
    const itemNums = norm.match(/\d+/g)?.join('-') || '';
    if (inputNums !== itemNums) return false;
    return norm.includes(cleanInput) || cleanInput.includes(norm);
  });
  if (partial) return partial;

  // 3. Concordancia difusa por tokens respetando números de línea/tienda
  const inputTokens = cleanInput.split(' ').filter(t => t.length > 2);
  if (inputTokens.length > 0) {
    let bestMatch = null;
    let maxMatchScore = 0;

    for (const item of STORE_CATALOG) {
      const norm = normalizeName(item.name);
      const itemNums = norm.match(/\d+/g)?.join('-') || '';
      if (inputNums !== itemNums) continue;

      const itemTokens = norm.split(' ').filter(t => t.length > 2);
      const matches = inputTokens.filter(t => itemTokens.includes(t)).length;
      const score = matches / Math.max(inputTokens.length, itemTokens.length);

      if (score > maxMatchScore && score > 0.6) {
        maxMatchScore = score;
        bestMatch = item;
      }
    }

    if (bestMatch) return bestMatch;
  }

  return null;
}

